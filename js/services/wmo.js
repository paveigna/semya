// WMO weather interpretation codes (used by Open-Meteo) → icon + Russian label.
const MAP = {
  0: ['☀️', 'Ясно'], 1: ['🌤️', 'Почти ясно'], 2: ['⛅', 'Переменная облачность'], 3: ['☁️', 'Пасмурно'],
  45: ['🌫️', 'Туман'], 48: ['🌫️', 'Изморозь'],
  51: ['🌦️', 'Слабая морось'], 53: ['🌦️', 'Морось'], 55: ['🌧️', 'Сильная морось'],
  56: ['🌧️', 'Ледяная морось'], 57: ['🌧️', 'Ледяная морось'],
  61: ['🌦️', 'Небольшой дождь'], 63: ['🌧️', 'Дождь'], 65: ['🌧️', 'Сильный дождь'],
  66: ['🌧️', 'Ледяной дождь'], 67: ['🌧️', 'Ледяной дождь'],
  71: ['🌨️', 'Небольшой снег'], 73: ['🌨️', 'Снег'], 75: ['❄️', 'Сильный снег'], 77: ['🌨️', 'Снежная крупа'],
  80: ['🌦️', 'Ливень'], 81: ['🌧️', 'Ливни'], 82: ['⛈️', 'Сильный ливень'],
  85: ['🌨️', 'Снегопад'], 86: ['❄️', 'Сильный снегопад'],
  95: ['⛈️', 'Гроза'], 96: ['⛈️', 'Гроза с градом'], 99: ['⛈️', 'Гроза с градом'],
};

export function describe(code, isDay = true) {
  const [icon, label] = MAP[code] || ['🌡️', '—'];
  if (!isDay && code <= 1) return ['🌙', code === 0 ? 'Ясная ночь' : label];
  return [icon, label];
}

export const isRain = (c) => [51, 53, 55, 56, 57, 61, 63, 65, 66, 67, 80, 81, 82, 95, 96, 99].includes(c);
export const isSnow = (c) => [71, 73, 75, 77, 85, 86].includes(c);
